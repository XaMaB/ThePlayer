import { mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
const root =
  process.env.THEPLAYER_DASH_FIXTURES ??
  path.join(os.tmpdir(), 'theplayer-dash-fixtures');
await mkdir(root, { recursive: true });
execFileSync(
  'ffmpeg',
  [
    '-hide_banner',
    '-loglevel',
    'error',
    '-y',
    '-f',
    'lavfi',
    '-i',
    'testsrc2=size=320x180:rate=25',
    '-f',
    'lavfi',
    '-i',
    'sine=frequency=440:sample_rate=48000',
    '-f',
    'lavfi',
    '-i',
    'sine=frequency=880:sample_rate=48000',
    '-map',
    '0:v',
    '-map',
    '0:v',
    '-map',
    '1:a',
    '-map',
    '2:a',
    '-c:v',
    'libx264',
    '-preset',
    'ultrafast',
    '-g',
    '50',
    '-keyint_min',
    '50',
    '-sc_threshold',
    '0',
    '-bf',
    '0',
    '-b:v:0',
    '250k',
    '-b:v:1',
    '700k',
    '-filter:v:1',
    'scale=640:360',
    '-c:a',
    'aac',
    '-b:a',
    '64k',
    '-metadata:s:a:0',
    'language=eng',
    '-metadata:s:a:1',
    'language=bul',
    '-t',
    '24',
    '-f',
    'dash',
    '-seg_duration',
    '2',
    '-use_template',
    '1',
    '-use_timeline',
    '1',
    '-init_seg_name',
    'init-$RepresentationID$.mp4',
    '-media_seg_name',
    'segment-$RepresentationID$-$Number%05d$.m4s',
    '-adaptation_sets',
    'id=0,streams=0,1 id=1,streams=2 id=2,streams=3',
    path.join(root, 'timeline.mpd'),
  ],
  { stdio: 'inherit' },
);
console.log('Generated original DASH test media in', root);
